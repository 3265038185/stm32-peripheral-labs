/*****************************************************************************
 * 文件名：Delay.c（System 系统层）
 * 所属工程：1-LED闪烁
 *
 * 【文件功能】
 *   提供毫秒、微秒、秒三种"软件延时"函数，供全工程调用。
 *   本工程的 LED 闪烁、按键延时等都需要它。
 *
 * 【涉及知识点：SysTick 系统滴答定时器】
 *   SysTick 是 Cortex-M3 内核自带的一个 24 位"倒计时"定时器：
 *   - 给它设置一个"重装值"LOAD 后，它从 LOAD 开始每来一个时钟脉冲减 1；
 *   - 减到 0 时（COUNTFLAG 位置 1），可以自动从 LOAD 重新装值继续倒数；
 *   - 本工程使用的时钟源是 HCLK（即系统时钟 72MHz），
 *     所以 SysTick 每数 1 次只花 1/72 微秒——这正是精确延时的基础。
 *
 * 【延时原理】
 *   72MHz 时钟下，数 1 下需要 1/72us，数 72 下就是 1us：
 *   所以"延时 xus 微秒" = 让 SysTick 从 72*xus 倒计时到 0。
 *   本文件用的方式是"查询法"：CPU 一直 while 死等计数器归零，
 *   延时期间 CPU 什么都干不了（这也叫"阻塞式延时"）。
 *
 * 【整体结构】
 *   Delay_us(微秒) ← 最底层；Delay_ms(毫秒) = 1000 次 Delay_us(1000)；
 *   Delay_s(秒)    = 1000 次 Delay_ms(1000)。层层嵌套实现。
 *****************************************************************************/
#include "stm32f10x.h"

/**
  * @brief  微秒级延时
  * @param  xus 延时时长，范围：0~233015
  * @retval 无
  */
/* ================= 中文详解 =================
 * 功能：延时 xus 微秒（例如 Delay_us(1000) 就是延时 1 毫秒）
 * 参数：xus —— 希望延时的微秒数
 * 返回值：无
 *
 * 【为什么 LOAD 要写 72 * xus？】
 *   本工程系统时钟 HCLK = 72MHz，SysTick 用 HCLK 做时钟源：
 *   每计数 1 次耗时 1/72 us，数 72 次 = 1us，数 72*xus 次 = xus 微秒。
 *   所以把 72*xus 写入重装值寄存器 LOAD。
 *   （范围上限 233015 = 0xFFFFFF / 72：因为 LOAD 是 24 位寄存器，
 *     最大只能写 2^24-1 = 16777215，除以 72 即约 233015us）
 *
 * 【四步流程】
 *   1. 写 LOAD：设定"从多少开始倒数"；
 *   2. 清 VAL：把当前计数值清零（避免上次残留值干扰，保证从头数起）；
 *   3. 写 CTRL = 0x05：bit0=1 使能 SysTick，bit2=1 选择时钟源为 HCLK；
 *   4. while 等待：CTRL 的 bit16（COUNTFLAG）变为 1，表示已数到 0；
 *   5. 写 CTRL = 0x04：bit0 清 0，关闭 SysTick，省电收工。
 */
void Delay_us(uint32_t xus)
{
	SysTick->LOAD = 72 * xus;				//设置定时器重装值：72*xus 个时钟脉冲 = xus 微秒
	SysTick->VAL = 0x00;					//清空当前计数值：确保从重装值重新开始倒数
	SysTick->CTRL = 0x00000005;				//设置时钟源为HCLK（bit2=1），启动定时器（bit0=1）
	while(!(SysTick->CTRL & 0x00010000));	//等待计数到0：bit16(COUNTFLAG) 置 1 时循环结束
	SysTick->CTRL = 0x00000004;				//关闭定时器：bit0=0，延时完成不再耗电
}

/**
  * @brief  毫秒级延时
  * @param  xms 延时时长，范围：0~4294967295
  * @retval 无
  */
/* ================= 中文详解 =================
 * 功能：延时 xms 毫秒
 * 参数：xms —— 希望延时的毫秒数
 * 返回值：无
 *
 * 【实现原理】
 *   1 毫秒 = 1000 微秒。这里用 while(xms--) 循环，
 *   每次调用 Delay_us(1000) 延时 1ms，共循环 xms 次。
 *   xms-- 是"先用后减"：先判断 xms 是否非 0，进入循环后再自减，
 *   所以总共正好执行 xms 次，循环结束时 xms 恰好变成 0。
 *   （uint32_t 最大 42 亿，所以理论上可以延时至 49 天，范围无忧）
 */
void Delay_ms(uint32_t xms)
{
	while(xms--)				//循环 xms 次，每次延时 1ms；xms 减到 0 时结束
	{
		Delay_us(1000);			//底层调用微秒延时：1000us = 1ms
	}
}
 
/**
  * @brief  秒级延时
  * @param  xs 延时时长，范围：0~4294967295
  * @retval 无
  */
/* ================= 中文详解 =================
 * 功能：延时 xs 秒
 * 参数：xs —— 希望延时的秒数
 * 返回值：无
 *
 * 【实现原理】
 *   与 Delay_ms 同理：1 秒 = 1000 毫秒，
 *   用 while(xs--) 循环 xs 次，每次调用 Delay_ms(1000) 延时 1 秒。
 *   注意循环变量是无符号数：调用时不要传 0 以下的值，
 *   否则无符号数下溢会变成一个巨大的数，导致延时极长。
 */
void Delay_s(uint32_t xs)
{
	while(xs--)				//循环 xs 次，每次延时 1s
	{
		Delay_ms(1000);		//底层调用毫秒延时：1000ms = 1s
	}
} 
