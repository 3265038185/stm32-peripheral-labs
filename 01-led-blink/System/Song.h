/*****************************************************************************
 * 文件名：Song.h（System 系统层头文件）
 * 说明：Song.c 的对外接口声明。
 *       Song() 用 LED 的点亮组合模拟《铃儿响叮当》的音符：
 *
 * 参数含义：
 *   x —— 音符编号 1~10，1 亮得最少（像低音），10 全部 10 个 LED 全亮（像最强音）；
 *   y —— 音符持续时间（毫秒），由 main.c 里的时值数组决定。
 *
 * 用法（见 main.c 被注释的代码）：
 *   预先准备好 pitch[]（音符序列）和 length[]（时值序列）两个数组，
 *   用循环逐个调用 Song(pitch[i], length[i]) 即可"播放"整首曲子。
 *****************************************************************************/
#ifndef __SONG_H__
#define __SONG_H__

//LED 音乐播放函数：x 为音符（1~10），y 为该音符持续毫秒数
void Song(int x,int y);

#endif
