/*****************************************************************************
 * 函数名：EXTI1_IRQHandler（EXTI 第 1 条外部中断线的中断服务函数）
 * 功能：  按键按下（PA1 出现下降沿）时被硬件自动调用，把 time 加 100
 * 参数：  无
 * 返回值：无
 *
 * 【EXTI 外部中断原理——它是怎么"自动"被调用的？】
 *   1. 初始化时（Hardware/EXTI.c 的 EXTIKey_Init()）：
 *      - 通过 GPIO_EXTILineConfig 把 PA1 引脚映射到 EXTI1 这条中断线；
 *      - 设置 EXTI_Trigger_Falling：只检测"高电平跳变到低电平"（下降沿）；
 *      - 在 NVIC 中使能 EXTI1 的中断通道。
 *   2. 运行中按下按键：PA1 从高电平（上拉电阻保证的）跳变到低电平，
 *      硬件立即把 EXTI1 的"挂起标志位"置 1，并向 NVIC 发出中断请求；
 *   3. 因为 NVIC 里 EXTI1 中断已使能，CPU 会暂停主循环、保存现场，
 *      自动跳转执行本函数——这就是"中断打断主程序"；
 *   4. 函数执行完后自动返回，主循环从刚才被打断的地方继续运行。
 *
 * 【为什么最后必须清挂起标志？】
 *   中断处理完必须调用 EXTI_ClearITPendingBit 把挂起标志位清零，
 *   否则硬件认为中断"还没被处理"，一退出中断马上又进入，形成死循环。
 *****************************************************************************/
void EXTI1_IRQHandler(void)
{
	if(EXTI_GetITStatus(EXTI_Line1)==SET)   //查询 EXTI1 挂起标志位：=SET 说明按键中断确实发生了
	{
		time+=100;                          //闪烁间隔 +100ms：按键按得越多，LED 闪得越慢
		EXTI_ClearITPendingBit(EXTI_Line1); //软件清零 EXTI1 挂起标志位，防止中断反复触发
		
	}
}

