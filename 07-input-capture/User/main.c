/*==============================================================================
 * 文件：main.c（主程序入口）
 * 功能：演示"TIM输入捕获 + PWM输出"的核心应用，整体流程如下：
 *       1. PWMInt_Init() ：配置TIM2输入捕获功能，测量 PA0 引脚上输入的
 *                          方波信号的"周期"（算出频率）和"高电平脉宽"；
 *       2. PWMOut_Init() ：配置TIM3 PWM输出功能，从 PA6 引脚输出方波；
 *       3. PWM_Set()     ：主循环里把TIM2测到的频率/脉宽，实时同步给TIM3，
 *                          让 TIM3 输出和输入一模一样的波形（频率和占空比一致）。
 * 用到的外设：TIM2（输入捕获）、TIM3（PWM输出）、GPIOA
 * 知识点：TIM定时器基本结构、输入捕获原理（测量两个边沿的时间差）、
 *         PWM输出原理、主从模式（TIM2捕获到周期后自动清零计数器）
 *============================================================================*/
#include "stm32f10x.h"     // STM32F10x系列的头文件：包含所有寄存器定义和标准库函数声明
#include "DELAY.h"         // 延时模块头文件（Delay_us/ms/s，本程序暂时没有直接用）
#include "OLED.h"          // OLED显示屏驱动头文件（本程序暂时没有用，为后续显示预留）
#include "PWM.h"           // PWM模块头文件：声明了下面要用的三个函数

/* 主函数：单片机一上电（复位）就从这里开始执行，整个程序只有一个死循环 */
int main(void)
{
	
	PWMOut_Init();	// ①初始化TIM3的PWM输出：PA6引脚输出PWM波，输出周期和占空比由ARR、CCR1决定
	PWMInt_Init();	// ②初始化TIM2的输入捕获：PA0引脚测量外部输入的方波，测出它的周期和高电平脉宽

	while(1)		// 主循环：程序复位后就一直在这里死循环，不断刷新
	{
		
		PWM_Set();	// ③把TIM2捕获到的"周期值"赋给TIM3的ARR（决定输出频率），
					//   把捕获到的"脉宽值"赋给TIM3的CCR1（决定输出占空比），
					//   从而实现"输入的波形什么样，输出的波形就什么样"
	}
	
	
}

