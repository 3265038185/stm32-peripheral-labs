/*============================================================================
  文件：Delay.c（软件延时函数 - 基于 SysTick 定时器）
  ----------------------------------------------------------------------------
  功能：提供微秒/毫秒/秒三种精度的阻塞式延时。
  ----------------------------------------------------------------------------
  用到的外设/知识点：SysTick（系统滴答定时器）
    - SysTick 是 Cortex-M3 内核自带的 24 位向下计数器，不属于任何外设，
      不需要初始化时钟，上电就能用；
    - 原理：把"需要延时的总计数个数"写进 LOAD 寄存器，
      计数器从该值开始每个时钟（72MHz，即每 1/72us）减 1，
      减到 0 时 COUNTFLAG 标志位置 1；
      程序"死等"这个标志位，就是精确延时。
  ----------------------------------------------------------------------------
  本文件用的是"查询方式"（while 等待），特点：
    - 简单直观，适合入门；
    - 缺点是延时期间 CPU 被占用，什么都干不了。
  ============================================================================*/
#include "stm32f10x.h"

/**
  * @brief  微秒级延时
  * @param  xus 延时时长，范围：0~233015
  * @retval 无
  */
/*  原理（配合注释理解）：
    1. SysTick->LOAD = 72 * xus：
       72MHz 时钟下 1us 计 72 个数，所以延时 xus 需要 72*xus 个计数，
       写入重装载寄存器 LOAD；
    2. SysTick->VAL = 0x00：
       写任意值即可清空当前计数值（VAL 是"只写清零"寄存器），
       防止上一次延时的残留计数影响本次精度；
    3. SysTick->CTRL = 0x00000005：
       bit0 = 1 使能 SysTick；bit2 = 1 选择 HCLK（72MHz）作为时钟源。
       注意没有开启 bit1（中断），因为我们用查询方式，不用中断；
    4. while(!(SysTick->CTRL & 0x00010000))：
       一直等 COUNTFLAG（bit16）变为 1，即计数减到 0，延时结束；
    5. SysTick->CTRL = 0x00000004：
       关闭 SysTick（bit0 清 0），省电，避免影响后续使用。
    为什么范围是 0~233015？
      因为 LOAD 是 24 位寄存器，最大 2^24-1 = 16777215，
      72 * xus <= 16777215 -> xus <= 233015。超过会溢出出错。  */
void Delay_us(uint32_t xus)
{
	SysTick->LOAD = 72 * xus;				//设置定时器重装值
	SysTick->VAL = 0x00;					//清空当前计数值
	SysTick->CTRL = 0x00000005;				//设置时钟源为HCLK，启动定时器
	while(!(SysTick->CTRL & 0x00010000));	//等待计数到0
	SysTick->CTRL = 0x00000004;				//关闭定时器
}

/**
  * @brief  毫秒级延时
  * @param  xms 延时时长，范围：0~4294967295
  * @retval 无
  */
/*  原理：1 毫秒 = 1000 微秒，所以循环调用 Delay_us(1000) 共 xms 次。
    用循环而不是直接"72*1000*xms"是因为 xms 可能很大，
    一次算出来的计数会超过 24 位 LOAD 的上限。  */
void Delay_ms(uint32_t xms)
{
	while(xms--)
	{
		Delay_us(1000);
	}
}
 
/**
  * @brief  秒级延时
  * @param  xs 延时时长，范围：0~4294967295
  * @retval 无
  */
/*  原理：1 秒 = 1000 毫秒，循环调用 Delay_ms(1000) 共 xs 次。  */
void Delay_s(uint32_t xs)
{
	while(xs--)
	{
		Delay_ms(1000);
	}
} 
