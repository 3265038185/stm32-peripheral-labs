/*============================================================================
  文件：Delay.h（软件延时 - 头文件）
  ----------------------------------------------------------------------------
  作用：防止重复包含 + 声明三个延时函数。
  注意：文件名叫 Delay.h，工程里引用时写成 #include "Delay.h" 或
        #include "DELAY.h" 都可以（Windows 文件系统不区分大小写，
        但 Keil 在 Linux/MAC 下会有区别，养成全小写的好习惯）。
  ============================================================================*/
#ifndef __DELAY_H
#define __DELAY_H

void Delay_us(uint32_t us);	// 微秒延时：us 范围 0~233015
void Delay_ms(uint32_t ms);	// 毫秒延时：最常用
void Delay_s(uint32_t s);	// 秒级延时

#endif
