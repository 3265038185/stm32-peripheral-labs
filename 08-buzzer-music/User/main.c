/*============================================================================
  文件：main.c（4-buzzer 项目主程序）
  ----------------------------------------------------------------------------
  功能：用 TIM3 输出 PWM 方波驱动【无源蜂鸣器】播放一首音乐。
  ----------------------------------------------------------------------------
  用到外设/知识点：
    1. PWM 输出（TIM3_CH1，引脚 PA6）：
       - 无源蜂鸣器必须靠"方波频率"才会发声，方波的频率就是音高（Do/Re/Mi）；
       - 本程序占空比固定为 50%，只改变 PWM 频率来改变音调。
    2. 定时器 TIM3：PSC 预分频 + ARR 自动重装，共同决定 PWM 输出频率。
    3. SysTick 延时（Delay_ms）：控制每个音符的播放时长（节奏）。
    4. 音乐原理：一个音符 = 一个频率（音高）+ 一个时长（节奏），
       所以把一段旋律拆成"频率数组 + 时长数组"两个表，逐个播放即可。
  ----------------------------------------------------------------------------
  整体结构：
    main.c —— 定义歌曲的频率/时长数组，死循环里依次播放
    PWM.c  —— TIM3 PWM 初始化 + PWM_Set() 设置音符频率
    Delay.c—— SysTick 延时
    OLED.c —— OLED 驱动（本程序暂未使用，可自行扩展显示歌名）
  ============================================================================*/
