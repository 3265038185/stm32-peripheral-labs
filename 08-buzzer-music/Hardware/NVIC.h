/*============================================================================
  文件：NVIC.h（外部中断按键 - 头文件）
  ----------------------------------------------------------------------------
  作用：
    1. 防止重复包含（#ifndef 三件套）；
    2. 声明本模块对外提供的两个函数：
       - NVICKey_Init()：初始化外部中断按键（PB12~15 + EXTI + NVIC）；
       - NVIC_GetKey() ：查询最近一次按下的键号。
  使用套路（在 main.c 中）：
      NVICKey_Init();              // 1. 初始化
      while(1)
      {
          if(NVIC_GetKey()==1)     // 2. 循环查询键号
          { ... }                  // 3. 按键 1 被按下后要做的处理
      }
  ============================================================================*/
#ifndef __NVIC_H__
#define __NVIC_H__

/*  初始化外部中断按键（GPIO + EXTI 中断线 + NVIC 优先级）  */
void NVICKey_Init(void);
/*  查询最近一次按下的键号：返回 1~4，无按键返回 0  */
unsigned int NVIC_GetKey(void);


#endif
