/*============================================================================
  文件：Key.h（独立按键驱动 - 头文件）
  ----------------------------------------------------------------------------
  头文件的作用：
    1. 防止重复包含：#ifndef __KEY_H__ / #define / #endif 三件套，
       同一个文件被 #include 两次也不会重复声明报错；
    2. 声明本模块函数：别的 .c 文件 #include 本文件后即可调用
       Key_Init、Key_GetNum 等函数；
    3. 定义按键别名宏：Key1~Key4 用 sys.h 的位带操作宏 PBin(n)，
       直接对应 GPIOB 的 IDR 输入寄存器第 n 位。
  ----------------------------------------------------------------------------
  位带操作小知识（sys.h 提供）：
    PBin(12) 展开后是"一个可以像变量一样读写的内存地址"，
    它对应 PB12 引脚的输入电平（IDR 寄存器 bit12）：
      PBin(12) == 0 表示 PB12 为低电平（按键按下）。
  ============================================================================*/
#ifndef __KEY_H__
#define __KEY_H__
#include "sys.h"
#define Key1 PBin(12)	// 按键 1：PB12 输入电平（0=按下，1=松开）
#define Key2 PBin(13)	// 按键 2：PB13 输入电平
#define Key3 PBin(14)	// 按键 3：PB14 输入电平
#define Key4 PBin(15)	// 按键 4：PB15 输入电平

/*  初始化按键 GPIO（PB12~PB15 上拉输入）  */
void Key_Init(void);

/*  简单轮询：返回被按下的键号（1~4），没按返回 0（带消抖，会等松开）  */
unsigned char Key_GetNum(void);
/*  状态机版：等待一次完整的"按下并松开"，返回键号（1~4）  */
unsigned char Key_GetState(void);
/*  状态机版：长按/短按/双击识别（针对 PB15）：
    返回 1=长按，2=短按，3=双击  */
unsigned char Key_One(void);
/*  状态机版：只检测 PB15，按下返回 1，200ms 内没按返回 0（供 Key_One 内部使用）  */
unsigned char Key_Oneneed(void);



#endif
