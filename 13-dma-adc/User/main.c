/*=============================================================================
 * 文件：main.c（DMA+ADC 项目的主函数文件）
 * 项目功能：用 ADC1 采集 PA0 引脚上的模拟电压，通过 DMA 自动搬运转换结果，
 *           最后把 128 个采样点画成一条波形曲线显示在 OLED 屏幕上。
 *
 * 用到的外设/知识点：
 *   1. ADC1  ：模拟-数字转换器，把 0~3.3V 的模拟电压量化成 0~4095 的数字
 *   2. DMA1  ：直接存储器访问，ADC 每转换完一次，结果自动存入数组，CPU 不用参与
 *   3. OLED  ：I2C 接口的 0.96 寸显示屏，用来画波形、显示数字
 *   4. SysTick：内核定时器，用于延时函数 Delay_ms
 *
 * 整体执行流程：
 *   1. OLED_Init()：初始化 OLED 显示屏（软件 I2C 模拟时序）
 *   2. AD_Init()  ：初始化 ADC1 + DMA1（详细原理见 Hardware/AD.c）
 *   3. 主循环 while(1) 中：把 AD_Value[0]~AD_Value[127] 这 128 个 ADC 转换结果
 *      逐个画到 OLED 上，横坐标 i 对应 0~127（屏幕列），纵坐标由电压换算而来
 *=============================================================================*/
#include "stm32f10x.h"                  // Device header
#include "Delay.h"                      // 延时函数头文件
#include "OLED.h"                       // OLED 显示函数头文件
#include "AD.h"                         // ADC+DMA 初始化函数头文件
int i = 0;                              // 全局变量 i：for 循环的计数变量，也代表屏幕横坐标（0~127）
int main(void)                          // 主函数：芯片复位后程序从这里开始执行
{
			
	/*模块初始化*/
	OLED_Init();				//OLED初始化：点亮屏幕、设置好 I2C 引脚和显示参数
			//AD初始化（注释掉的空位置，真正的初始化在下面）
	
	//Delay_ms(100);			//被注释掉的延时，如果 OLED 上电不稳定可取消注释等待 100ms

	AD_Init();					//AD初始化：配置 ADC1 连续转换 + DMA1 循环搬运，此后 AD_Value 数组会被自动填充
	while (1)					//主循环：程序不断重复执行 {} 内的代码，实现"边采样边显示"
	{
		/* 把 128 个采样点画成一条波形曲线 */
		for(i=0;i<128;i++)		//循环 128 次，i 从 0 到 127，正好覆盖屏幕 128 列像素
		{
			/* 在 (i, 纵坐标) 处画一个点：
			 * AD_Value[i] 是第 i 个 ADC 转换结果（0~4095）
			 * 除以 4095 得到 0.0~1.0 的比例（相当于电压/3.3V）
			 * 再乘以 63，因为屏幕纵向是 0~63 行像素，这样电压 3.3V 时点在屏幕最上方
			 * 强制转成 int 是为了把浮点数变成整数坐标，供画点函数使用 */
			OLED_DrawPoint(i,(int)((float)AD_Value[i]/4095*63));
		}
		OLED_Clear();			//清屏：画完一帧后擦掉旧画面，再进入下一轮循环重新画
		/* 说明：因为 DMA 是循环模式、ADC 是连续转换，AD_Value 里的数据一直在
		 * 实时刷新，所以每画一帧看到的都是最新波形，类似一个简易示波器 */
//		for(i=1;i<5;i++)
//		{
//			OLED_ShowNum(i,1,AD_Value[i]/4095*63,9);
//		}
		//OLED_Clear();
		
	}
}
