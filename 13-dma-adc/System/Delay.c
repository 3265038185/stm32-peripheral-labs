/*=============================================================================
 * 文件：Delay.c（延时函数文件）
 * 功能：基于 SysTick（系统滴答定时器）实现微秒、毫秒、秒三种精度的延时。
 *
 * 用到的外设/知识点（初学者必懂）：
 *   1. SysTick 是 Cortex-M3 内核自带的 24 位"倒计数"定时器，
 *      不需要配置时钟树，上电就能用，专门用来产生固定延时
 *   2. 本程序用的时钟源是 HCLK（系统时钟）72MHz，即每 1 微秒计数器减 72 次
 *   3. 延时原理（以 Delay_us 为例）：
 *      a. 把"要延时的微秒数 x 72"写入重装载寄存器 LOAD
 *      b. 计数器从 LOAD 开始每次时钟脉冲减 1
 *      c. 减到 0 时状态寄存器 COUNTFLAG（CTRL 的 bit16）被置 1
 *      d. 程序不断查询这个标志位，一变为 1 就说明时间到了
 *   4. 这种"轮询查询"方式会占用 CPU，但实现简单，适合短延时
 *
 * 寄存器说明（直接操作寄存器，比标准库更底层）：
 *   SysTick->LOAD ：重装载值寄存器（24 位，最大 16777215）
 *   SysTick->VAL  ：当前计数值寄存器（写任意值即清零）
 *   SysTick->CTRL ：控制寄存器
 *                   bit0  ENABLE    —— 使能计数器
 *                   bit1  TICKINT   —— 使能中断（本程序不用）
 *                   bit2  CLKSOURCE —— 时钟源（0=HCLK/8，1=HCLK 72MHz）
 *                   bit16 COUNTFLAG —— 计数到 0 时硬件置 1
 *=============================================================================*/
#include "stm32f10x.h"		//Device header（包含 SysTick 寄存器定义）

/**
  * @brief  微秒级延时
  * @param  xus 延时时长，范围：0~233015（微秒）
  * @retval 无
  */
/* 原理：72MHz 时钟下，1 微秒计数器走 72 下，
 * 所以重装值 = 72 * xus（见函数体逐行注释） */
void Delay_us(uint32_t xus)
{
	SysTick->LOAD = 72 * xus;				//设置定时器重装值：xus 微秒需要走 72*xus 个时钟
	SysTick->VAL = 0x00;					//清空当前计数值（不清零的话可能立即溢出，延时不准）
	SysTick->CTRL = 0x00000005;				//设置时钟源为HCLK，启动定时器
	/* 0x05 = 二进制 0101：bit0(使能)=1，bit2(时钟源选 HCLK 72MHz)=1，
	 * bit1(中断)保持 0 = 不用中断，采用查询方式 */
	while(!(SysTick->CTRL & 0x00010000));	//等待计数到0
	/* 循环里不断读 CTRL 的 bit16（COUNTFLAG）：计数到 0 时硬件置 1，
	 * 非 0 时退出循环，说明延时时间到 */
	SysTick->CTRL = 0x00000004;				//关闭定时器
	/* 0x04 = bit2 置 1（保留时钟源设置）、bit0 清零（停止计数），
	 * 这样不影响下次重新设置 LOAD */
}

/**
  * @brief  毫秒级延时
  * @param  xms 延时时长，范围：0~4294967295（毫秒）
  * @retval 无
  */
/* 原理：调用 1000 次 Delay_us(1000) 就是 1 毫秒，
 * 循环 xms 次即可得到 xms 毫秒。注意 xms-- 是"先用后减"：
 * 先判断 xms 是否为 0，非 0 则执行循环体并自减 */
void Delay_ms(uint32_t xms)
{
	while(xms--)		//循环 xms 次（xms=0 时循环结束）
	{
		Delay_us(1000);	//每次延时 1000 微秒 = 1 毫秒
	}
}
 
/**
  * @brief  秒级延时
  * @param  xs 延时时长，范围：0~4294967295（秒）
  * @retval 无
  */
/* 原理：与毫秒延时同理，循环 xs 次，每次调用 Delay_ms(1000) = 1 秒 */
void Delay_s(uint32_t xs)
{
	while(xs--)			//循环 xs 次
	{
		Delay_ms(1000);	//每次延时 1000 毫秒 = 1 秒
	}
} 
