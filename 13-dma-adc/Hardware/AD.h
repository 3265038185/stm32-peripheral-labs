/*=============================================================================
 * 文件：AD.h（AD.c 的头文件）
 * 功能：声明 AD.c 中的函数和全局变量，供其他文件（如 main.c）调用。
 *
 * 头文件的作用（初学者必懂）：
 *   1. 防止重复包含：用 #ifndef / #define / #endif 包裹，同一个头文件
 *      被 include 多次也不会报错（编译原理：条件编译，第一次定义宏后
 *      再次进入时整个内容被跳过）
 *   2. 声明（不是定义）函数：让别的 .c 文件知道"有这个函数，可以调用"
 *   3. extern 声明变量：告诉编译器"这个变量定义在别的文件里"，
 *      这样 main.c 就能直接使用 AD_Value 数组里的数据
 *=============================================================================*/
#ifndef __AD_H			//如果没有定义过宏 __AD_H（即头文件还没被包含过）
#define __AD_H			//就定义宏 __AD_H，并执行下面内容

extern uint16_t AD_Value[128];	//声明全局数组：DMA 搬运 ADC 转换结果的存放处
								//实际定义在 AD.c 中，这里用 extern 表示"引用外部的"
								//【重点】main.c 里画波形用的就是它，值范围 0~4095

void AD_Init(void);				//声明 AD 初始化函数：配置 ADC1+DMA1 并开始连续转换

#endif							//结束条件编译：与 #ifndef 配对使用
