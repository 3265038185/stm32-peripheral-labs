/* ============================================================================
 * 文件说明（PWM.h —— PWM 呼吸灯头文件）
 * ----------------------------------------------------------------------------
 * 声明 PWM.c 提供的 2 个函数：
 *   PWM_Init()   初始化 TIM4 的 PWM 输出（通道3 -> PB8）
 *   PWM_LED()    呼吸灯效果（占空比 0→100→0 循环 3 次）
 * ========================================================================== */
#ifndef __PWM_H__
#define __PWM_H__

void PWM_Init(void);         // 初始化 PWM：TIM4 通道3（PB8）输出，频率 1kHz
void PWM_LED(void);          // 呼吸灯效果：亮度渐亮再渐暗，循环 3 遍
#endif
