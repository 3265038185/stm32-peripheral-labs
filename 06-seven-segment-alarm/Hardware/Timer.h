/* ============================================================================
 * 文件说明（Timer.h —— 定时器头文件）
 * ----------------------------------------------------------------------------
 * 声明 Timer.c 提供的 2 个函数：
 *   Timer2_Init()   初始化 TIM2：每 1 秒产生一次更新中断（倒计时"秒"的来源）
 *   Timer3_Init()   初始化 TIM3：每 1 毫秒产生一次更新中断（数码管扫描节拍）
 * 两个定时器的中断服务函数（TIM2_IRQHandler / TIM3_IRQHandler）
 * 写在 main.c 中。
 * ========================================================================== */
#ifndef __TIMER_H__
#define __TIMER_H__
void Timer2_Init(void);      // 初始化 TIM2（1 秒中断一次，用于倒计时）
void Timer3_Init(void);      // 初始化 TIM3（1 毫秒中断一次，用于数码管扫描）
#endif
