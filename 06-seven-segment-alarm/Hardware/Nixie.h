/* ============================================================================
 * 文件说明（Nixie.h —— 数码管驱动头文件）
 * ----------------------------------------------------------------------------
 * 声明 Nixie.c 提供的 3 个函数：
 *   Nixie_Init()        初始化段选/位选引脚
 *   Nixie_ShowNum()     在某一位显示数字（不带小数点）
 *   Nixie_ShowDotNum()  在某一位显示数字（带小数点）
 * ========================================================================== */
#ifndef __NIXIE_H__
#define __NIXIE_H__

void Nixie_Init(void);                 // 初始化数码管引脚（PA0~PA7 段选、PB12~PB15 位选）
void Nixie_ShowNum(int x,int y);       // 在第 x 位(1~4)显示数字 y(0~9)
void Nixie_ShowDotNum(int x,int y);    // 在第 x 位(1~4)显示数字 y(0~9)，带小数点
#endif
