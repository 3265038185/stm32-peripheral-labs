/* ============================================================================
 * 文件说明（led.h —— LED 头文件）
 * ----------------------------------------------------------------------------
 * 内容：
 *   1. 用位带操作宏把 4 个 LED 的引脚"起个名字"：
 *      LED0 = PA9、LED1 = PA10、LED2 = PA11、LED3 = PA8
 *      以后代码里写 LED0 = 0 / LED0 = 1 就能单独控制对应引脚输出
 *   2. 声明 LED.c 提供的两个函数：LED_Init() 初始化、LED_Run() 流水灯
 * ========================================================================== */
#ifndef __LED_H
#define __LED_H	 
#include "sys.h"                 // 引入位带操作宏 PAout(n) 等

// 注意：LED0 与 LED3 的引脚编号不是连续的（8、9、10、11），
//       写代码时不要想当然地认为 LED3 就是 PA11
#define LED0 PAout(9)            // 第 1 个 LED 接在 PA9（PAout(9) = 控制 PA9 输出）
#define LED1 PAout(10)           // 第 2 个 LED 接在 PA10
#define LED2 PAout(11)           // 第 3 个 LED 接在 PA11
#define LED3 PAout(8)            // 第 4 个 LED 接在 PA8



// 函数声明：LED 模块对外只提供这两个函数
void LED_Init(void);             // 初始化 LED 引脚（PA8~PA11 推挽输出）
void LED_Run(void);              // 流水灯效果：4 个 LED 依次点亮再熄灭
		 				    
#endif

















