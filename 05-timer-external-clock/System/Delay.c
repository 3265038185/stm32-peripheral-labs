/*===============================================================================
 * 文件名称：Delay.c（软件延时文件）
 * 模块功能：基于 SysTick（系统滴答定时器）实现微秒/毫秒/秒级延时
 * 用到的外设/知识点：
 *   1. SysTick：Cortex-M3 内核自带的 24 位"递减计数器"，
 *      不需要像外设定时器那样开 RCC 时钟，直接操作它的寄存器即可
 *   2. 延时原理：72MHz 主频下，1 秒 = 72000000 个时钟周期，
 *      所以 1 微秒 = 72 个周期，让 SysTick 从 "72 * xus" 倒数到 0，
 *      就"死等"了 xus 微秒
 * 注意：本延时是"阻塞式"的，延时期间 CPU 一直在空转，什么也干不了，
 *       所以延时不宜过长（比如几百毫秒以上），否则会拖慢主程序
 *===============================================================================
 */
#include "stm32f10x.h"

/**
  * @brief  微秒级延时
  * @param  xus 延时时长，范围：0~233015
  * @retval 无
  */
/* 实现原理（操作 SysTick 的 4 个步骤）：
   1. SysTick->LOAD = 72 * xus：
      —— 设置"重装载值"。因为主频 72MHz，每微秒走过 72 个时钟周期，
         要延时 xus 微秒就装进 72*xus 个周期数
   2. SysTick->VAL = 0x00：
      —— 清空当前计数值（不清的话，LOAD 装新值后计数器是从"上次的残余值"
         继续倒数，延时就不准了）
   3. SysTick->CTRL = 0x00000005：
      —— 二进制 0101 = 第2位(CLKSOURCE=1 时钟源选 HCLK=72MHz) + 第0位(ENABLE=1 启动)
   4. while(!(SysTick->CTRL & 0x00010000)):
      —— 轮询标志位：CTRL 的第 16 位（COUNTFLAG）在计数到 0 时自动置 1，
         没置 1 就一直在这一行死等（这就是"阻塞延时"）
   5. SysTick->CTRL = 0x00000004：
      —— 二进制 0100 = 第2位(CLKSOURCE=1) + 第0位(ENABLE=0 关闭定时器)，
         延时结束，关闭 SysTick 省电
   注：范围 0~233015 是因为 LOAD 只有 24 位，最大 0xFFFFFF=16777215，
       16777215/72 ≈ 233015 微秒 */
void Delay_us(uint32_t xus)
{
	SysTick->LOAD = 72 * xus;				//设置定时器重装值
	SysTick->VAL = 0x00;					//清空当前计数值
	SysTick->CTRL = 0x00000005;				//设置时钟源为HCLK，启动定时器
	while(!(SysTick->CTRL & 0x00010000));	//等待计数到0
	SysTick->CTRL = 0x00000004;				//关闭定时器
}

/**
  * @brief  毫秒级延时
  * @param  xms 延时时长，范围：0~4294967295
  * @retval 无
  */
/* 实现原理：毫秒 = 微秒的 1000 倍，
   调用 xms 次 Delay_us(1000)（每次延 1ms），循环 xms 次就是 xms 毫秒 */
void Delay_ms(uint32_t xms)
{
	while(xms--)	// 循环 xms 次（先判断再自减，最后一次为 0 时退出）
	{
		Delay_us(1000);	// 每次延时 1000 微秒 = 1 毫秒
	}
}
 
/**
  * @brief  秒级延时
  * @param  xs 延时时长，范围：0~4294967295
  * @retval 无
  */
/* 实现原理：秒 = 毫秒的 1000 倍，循环调用 Delay_ms(1000) 即可 */
void Delay_s(uint32_t xs)
{
	while(xs--)	// 循环 xs 次
	{
		Delay_ms(1000);	// 每次延时 1000 毫秒 = 1 秒
	}
} 
