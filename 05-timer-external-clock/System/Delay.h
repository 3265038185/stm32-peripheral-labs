/*===============================================================================
 * 文件名称：Delay.h（软件延时模块头文件）
 * 模块功能：声明基于 SysTick 的延时函数
 * 使用注意：延时是阻塞式的，期间 CPU 空转；延时时间过长会影响程序实时性
 *===============================================================================
 */
#ifndef __DELAY_H		// 防止重复包含
#define __DELAY_H

void Delay_us(uint32_t us);	// 微秒级延时（范围 0~233015 微秒）
void Delay_ms(uint32_t ms);	// 毫秒级延时
void Delay_s(uint32_t s);	// 秒级延时

#endif	// 防止重复包含结束
