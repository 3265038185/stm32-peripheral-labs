/*===============================================================================
 * 文件名称：NVIC.h（中断控制器模块头文件）
 * 模块功能：声明 NVIC.c 里对外提供的函数
 * 知识点：NVIC = Nested Vectored Interrupt Controller（嵌套向量中断控制器），
 *         是 Cortex-M3 内核里的"中断管家"，负责给中断排队、决定优先级
 *===============================================================================
 */
#ifndef __NVIC_H__
#define __NVIC_H__

void NVICKey_Init(void);	// 初始化外部中断按键（PB12~15 + EXTI 下降沿中断）
unsigned int NVIC_GetKey(void);	// 获取中断里记录的按键号（1~4，0 表示无按键）


#endif	// 防止重复包含结束
