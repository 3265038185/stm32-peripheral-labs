/*=============================================================================
 * 文件：Delay.h（Delay.c 的头文件）
 * 功能：声明延时函数，供其他文件（如 main.c、Key.c）调用。
 * 说明：延时基于 SysTick 定时器实现，时钟 72MHz
 *=============================================================================*/
#ifndef __DELAY_H			//如果没定义过 __DELAY_H（头文件还没被包含过）
#define __DELAY_H			//就定义 __DELAY_H，并执行下面的声明

void Delay_us(uint32_t us);	//声明：微秒级延时（范围 0~233015 微秒）
void Delay_ms(uint32_t ms);	//声明：毫秒级延时
void Delay_s(uint32_t s);	//声明：秒级延时

#endif					//结束条件编译
