/*=============================================================================
 * 文件：main.c（波形项目的主函数文件）
 * 项目功能：用 ADC 采集输入信号的电压，配合定时器 TIM3 定时采样，
 *           当检测到信号电平"稳定在中间值附近"时，把最近 128 个采样点
 *           画成波形显示在 OLED 上（一个简易"示波器"）。
 *
 * 用到的外设/知识点：
 *   1. ADC1（PA0 通道0）：模拟-数字转换，单次转换，结果 0~4095 对应 0~3.3V
 *   2. TIM3（定时器中断）：定时触发中断，在中断里定时采样 ADC
 *      （预分频 72-1 把 72MHz 降到 1MHz，计数 100-1，溢出周期 = 100us，
 *       即每 100 微秒采一次样）
 *   3. 中断采样 + 主循环显示：中断里把数据存进数组，主循环里画波形，
 *      两者通过标志位（flagc、flaga、flagd 等）配合
 *   4. OLED 画点显示波形（128 个点，横坐标 0~127，纵坐标 0~63）
 *
 * 整体工作流程：
 *   1. 初始化 ADC、OLED、TIM3
 *   2. TIM3 中断每 100us 采一次 ADC，结果存进 AD_Value[a]，a 到 128 归零
 *   3. 主循环判断：若最近两次采样值都在"中间值±100"范围内（信号稳定），
 *      且之前没采完过一屏，则先停定时器、再启动定时器重新采样
 *   4. 当一屏 128 个点采完后（flagc==1），清屏并把 128 个点画到 OLED 上
 *
 * 注：文件中有大量被注释掉的调试代码，理解主流程后可以忽略它们
 *=============================================================================*/
#include "stm32f10x.h"                  // Device header
