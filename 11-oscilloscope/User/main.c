	while (1)		//主循环：不断检测采样状态并刷新波形显示
	{
		/* 触发条件判断：找"信号稳定段"作为触发点，让波形每次都从同一位置开始画，
		 * 效果类似示波器的"触发功能"，画面稳定不飘。
		 * 4095/2 ≈ 2047.5 是 1.65V 对应的 ADC 值（满量程一半）：
		 *   条件1：Same 在 2047.5±100 范围内（电平接近中间值）
		 *   条件2：flagd==0（上一次触发还没完成，避免重复触发）
		 *   条件3：Same2 > Same（信号处于上升沿，检测到上升沿过中点才触发） */
		if( 4095/2-100<Same&&Same<((uint16_t)4095/2+100)&&flagd==0&&Same2>Same)
		{
			//OLED_Clear();
			
			/* 触发成功！执行"重采"三步曲： */
			TIM_Cmd(TIM3,DISABLE);		//先停定时器：暂停中断采样
			flagc = 0;					//清"一屏采完"标志
			flagb = 0;					//清"开始采样"标志（中断里靠它判断是否从头存）
			TIM_Cmd(TIM3,ENABLE);		//再开定时器：重新从 AD_Value[0] 开始采样
			flaga= 1;					//置位：表示"新一屏采样正在进行"
			
			flagd = 1;					//置位：防止这次触发过程中再次触发
			
		}
		//TIM_Cmd(TIM3,DISABLE);
		/* 显示条件判断：flagc==1 表示 TIM3 中断里已经采满 128 个点（一屏），
		 * flaga==1 表示这一屏确实是刚触发的数据，两个条件都满足才画 */
		if(flagc == 1&&flaga ==1)
			{
				OLED_Clear();			//清屏：擦掉上一帧画面
				for(i=0;i<128;i++)		//循环 128 次，画 128 个采样点
				{
				/* 在 (i, 纵坐标) 处画一个点：
				 * AD_Value[i] 是第 i 个采样值（0~4095）
				 * /4095*63：按比例映射到屏幕 0~63 的纵向范围（0V 在屏底，3.3V 在屏顶） */
				OLED_DrawPoint(i,(uint8_t)((float)AD_Value[i]/4095*63));
				}
				
				flaga = 0;				//清标志：这一屏已经画完
				flagd = 0;				//清标志：允许下一次触发
			}
	}
		
