	Delay_ms(100);		//延时 100ms：等 OLED 和 ADC 稳定后再开定时器
	Tim_Init();			//定时器初始化：配置 TIM3 每 100us 进一次中断采样
	
//	OLED_DrawPoint(i,(uint8_t)((float)AD_Value[(uint8_t)7.8*i]/4095*63));
