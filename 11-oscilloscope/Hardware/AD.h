/*=============================================================================
 * 文件：AD.h（AD.c 的头文件）
 * 功能：声明 AD.c 中的函数和全局变量，供 main.c 等文件调用。
 *
 * 声明原理（初学者必懂）：
 *   1. extern 变量声明：告诉编译器"这些变量定义在 AD.c 中"，
 *      main.c 里就能直接读写它们
 *   2. 中断和主循环"共用"这些全局变量（标志位通信），
 *      是"定时器中断采样 -> 主循环显示波形"两个模块之间的桥梁
 *   3. 注意：被注释的 flagt 在 AD.c 中也没有定义（同样是调试残留），
 *      如果取消注释使用会编译报错，需要两边同步
 *=============================================================================*/
#ifndef __AD_H			//如果没定义过 __AD_H（头文件还没被包含过）
#define __AD_H			//就定义 __AD_H，并执行下面的声明

extern uint16_t Same;		//声明：最近一次采样的 ADC 值（触发判断用）
extern uint16_t Same2;		//声明：上一次采样的 ADC 值（上升沿触发判断用）
extern uint16_t AD_Value[128];	//声明：采样结果数组（实际定义在 AD.c，开的是 1000 个元素）
extern uint8_t flagc;		//声明：一屏采满标志（=1 时主循环画波形）
extern uint8_t flagb;		//声明：新一轮采样标志（=0 时中断把下标清零）
extern uint8_t flagt;		//声明：预留标志（当前未使用，定义在 AD.c 中被注释）
extern uint8_t flage;		//声明：新一屏第一个点标志（触发判断用）
void Tim_Init(void);		//声明：定时器 TIM3 初始化函数（每 100us 中断一次）
void AD_Init(void);			//声明：ADC 初始化函数（PA0 单次转换）
uint16_t AD_GetValue(void);	//声明：软件触发采样一次，返回 0~4095

#endif					//结束条件编译
