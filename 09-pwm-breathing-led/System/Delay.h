/* ============================================================================
 * 文件说明：Delay.h —— 延时函数头文件（对应 Delay.c）
 * ----------------------------------------------------------------------------
 * 使用示例：
 *   Delay_us(500);   // 延时 500 微秒（0.5ms）
 *   Delay_ms(10);    // 延时 10 毫秒（呼吸灯每级亮度停留时间）
 *   Delay_s(2);      // 延时 2 秒
 * 注意：三个函数都是阻塞式延时，期间 CPU 不执行其他代码。
 * ========================================================================== */

#ifndef __DELAY_H            // 头文件保护，防止重复包含
#define __DELAY_H

void Delay_us(uint32_t us);  // 微秒级延时（0~233015）
void Delay_ms(uint32_t ms);  // 毫秒级延时
void Delay_s(uint32_t s);    // 秒级延时

#endif
