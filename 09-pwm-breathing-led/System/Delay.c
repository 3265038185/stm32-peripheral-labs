/* ============================================================================
 * 文件说明：Delay.c —— 软件延时库（基于 SysTick 系统滴答定时器）
 * ----------------------------------------------------------------------------
 * 【原理】
 *   SysTick（系统滴答定时器）是 Cortex-M3 内核自带的 24 位倒计数定时器，
 *   不用配置外设时钟，直接操作它的 3 个寄存器就能实现精确延时：
 *     - LOAD（重装值）：写入倒计数的初值
 *     - VAL（当前值）：读当前计数，写 0 可清零
 *     - CTRL（控制寄存器）：bit2 选时钟源、bit0 使能、bit16 是"数到 0"的标志
 *   工作过程：VAL 从 LOAD 开始每个时钟周期减 1，减到 0 时 COUNTFLAG(bit16) 置 1。
 *
 * 【延时时间的计算】
 *   系统时钟 HCLK = 72MHz = 每秒数 72000000 下。
 *   延时 x 微秒需要计数 = 72 × x 下（1us = 72 个时钟周期）。
 *   所以：LOAD = 72 * xus 就是让定时器数 xus 微秒。
 *   用法：Delay_us(1000) 就是 1ms；Delay_ms(1000) 就是 1s。
 *
 * 【注意】
 *   1. 这是"阻塞式"延时：延时期间 CPU 一直在空转等计数器归零，
 *      干不了别的事。定时器中断延时（如 TIM 中断）可以避免这个问题。
 *   2. 本函数基于 72MHz 主频，如果改了系统主频，72 这个系数也要改。
 *   3. 本工程呼吸灯里 Delay_ms(10) 的作用：让占空比每变化 1% 停留 10ms，
 *      这样人眼能看到亮度平滑过渡（变亮/变暗全程约 1 秒）。
 * ========================================================================== */

#include "stm32f10x.h"

/**
  * @brief  微秒级延时
  * @param  xus 延时时长，范围：0~233015
  * @retval 无
  */
/* 详细步骤：
   1. SysTick->LOAD = 72*xus：设置倒计数初值（数这么多下 = xus 微秒）；
   2. SysTick->VAL = 0：清空当前计数（不清空可能马上数到 0，延时变短）；
   3. SysTick->CTRL = 0x05：
      - bit0 = 1：使能 SysTick（开始倒计数）
      - bit2 = 1：时钟源选 HCLK（72MHz）
   4. while(!(CTRL & 0x00010000))：等待 bit16(COUNTFLAG) 变 1，
      这个位在计数器数到 0 时被硬件置 1；
   5. SysTick->CTRL = 0x04：关闭 SysTick（bit0 清 0），并清掉计数标志。 */
void Delay_us(uint32_t xus)
{
	SysTick->LOAD = 72 * xus;				//设置定时器重装值
	SysTick->VAL = 0x00;					//清空当前计数值
	SysTick->CTRL = 0x00000005;				//设置时钟源为HCLK，启动定时器
	while(!(SysTick->CTRL & 0x00010000));	//等待计数到0
	SysTick->CTRL = 0x00000004;				//关闭定时器
}

/**
  * @brief  毫秒级延时
  * @param  xms 延时时长，范围：0~4294967295
  * @retval 无
  */
/* 原理：循环 xms 次，每次调用 Delay_us(1000)（即 1ms），累计就是 xms 毫秒。
 * 为什么不直接用 Delay_us(xms*1000)？因为 SysTick 是 24 位计数器，
 * 最大计数值 = 2^24-1 = 16777215，对应约 233ms。超过会溢出，
 * 所以用循环多次的方式，xms 理论上可以任意大。 */
void Delay_ms(uint32_t xms)
{
	while(xms--)              // xms 次循环，每循环一次延时 1ms
	{
		Delay_us(1000);       // 延时 1ms
	}
}
 
/**
  * @brief  秒级延时
  * @param  xs 延时时长，范围：0~4294967295
  * @retval 无
  */
/* 原理：循环 xs 次，每次调用 Delay_ms(1000)（即 1s） */
void Delay_s(uint32_t xs)
{
	while(xs--)               // xs 次循环，每循环一次延时 1s
	{
		Delay_ms(1000);       // 延时 1s
	}
} 
