/* ============================================================================
 * 文件说明：main.c —— 4-PWM呼吸灯 主程序（主函数入口）
 * ----------------------------------------------------------------------------
 * 项目名称：4-PWM呼吸灯
 * 开发平台：STM32F103C8T6（标准库 V3.5，江协科技风格）
 *
 * 【本文件的作用】
 *   1. 调用 PWM_Init() 完成 PWM 输出的初始化（TIM2 的通道 1，输出到 PA0）；
 *   2. 在主循环 while(1) 中，通过不断修改 TIM2 比较寄存器 CCR 的值，
 *      来循环改变 PWM 波形的占空比，从而让 LED 呈现"呼吸"一样忽明忽暗的效果。
 *
 * 【用到的外设/知识点】
 *   - TIM2 定时器：PWM 模式 1 输出（PWM.c 中配置）
 *   - 占空比公式：占空比 = CCR / (ARR + 1) × 100%
 *   - TIM_SetCompare1() 标准库函数：本质就是修改 TIM2->CCR1 寄存器的值
 *
 * 【呼吸灯原理】
 *   人眼有"视觉暂留"效应，当 PWM 频率足够高（本工程约 1kHz）时，
 *   人眼看到的 LED 亮度 ≈ 占空比。所以只要让占空比从 0% 慢慢增加到 100%，
 *   再从 100% 慢慢减小到 0%，循环往复，就实现了"呼吸"效果。
 * ========================================================================== */

#include "stm32f10x.h"     // STM32F103 标准库头文件（包含所有寄存器定义和外设函数声明）
#include "DELAY.h"         // 软件延时库（提供 Delay_ms 毫秒延时）
#include "OLED.h"          // OLED 屏幕驱动库（本工程未实际使用，可忽略）
#include "Key.h"           // 按键驱动库（本工程未实际使用，可忽略）
#include "PWM.h"           // PWM 输出初始化库（本工程核心外设）

uint8_t i;                 // 全局循环变量：用来控制占空比从 0 到 100 变化（0~100 共 101 个亮度等级）

int main(void)             // C 语言程序入口，上电复位后从这里开始执行
{
	PWM_Init();            // 初始化 PWM：开启 TIM2 时钟、配置 PA0 为复用推挽输出、
	                       // 设置预分频 PSC=719、自动重装值 ARR=99，最后使能 TIM2

	while(1)               // 主循环：单片机程序通常都写在这里，永远循环执行
	{
		/* 第一个 for 循环：呼吸灯"变亮"阶段（占空比从 0% 升到 100%） */
		for(i=0;i<=100;i++)// i 从 0 逐渐加到 100，共 101 次
		{
			TIM_SetCompare1(TIM2,i);  // 把 CCR1 设为 i，即修改 TIM2 的 CCR1 比较寄存器
			                           // 占空比 = CCR1/(ARR+1) = i/100，i 越大 LED 越亮
			Delay_ms(10);             // 延时 10ms，让亮度"停留"一会儿，变化才不会太突兀
		}

		/* 第二个 for 循环：呼吸灯"变暗"阶段（占空比从 100% 降到 0%） */
		for(i=0;i<=100;i++)
		{
			TIM_SetCompare1(TIM2,100-i);  // CCR1 = 100 - i，i 增加时 CCR1 减小
			                               // 占空比从 100% 逐渐降到 0%，LED 越来越暗
			Delay_ms(10);                 // 同样延时 10ms
		}
		
		/* 两个循环合在一起：亮→暗→亮→暗……无限循环，就像人呼吸一样 */
	}

}

