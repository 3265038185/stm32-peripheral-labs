/* ============================================================================
 * 文件说明：Key.h —— 按键驱动头文件（对应 Key.c）
 * ----------------------------------------------------------------------------
 * 【作用】
 *   1. 用 #ifndef 防止重复包含；
 *   2. 用宏定义给 4 个按键起"别名"（Key1~Key4），方便写代码；
 *   3. 声明 Key.c 里的函数，供 main 等其他文件调用。
 *
 * 【宏定义解释】
 *   PBin(12) 是 sys.h 里用"位带操作"定义的宏：
 *   它把 GPIOB 输入寄存器 IDR 的第 12 位映射成一个独立的 32 位地址，
 *   之后写 Key1 就等于读 GPIOB 引脚 12 的电平（1 或 0）。
 *   按键一端接地，所以 Key1 == 0 表示按键按下。
 * ========================================================================== */

#ifndef __KEY_H__          // 头文件保护：防止重复包含
#define __KEY_H__
#include "sys.h"           // 引入位带操作宏 PBin()/PBout() 等（本文件用到 PBin）
#define Key1 PBin(12)      // 按键1 对应 GPIOB 引脚12：按下时为 0（低电平）
#define Key2 PBin(13)      // 按键2 对应 GPIOB 引脚13
#define Key3 PBin(14)      // 按键3 对应 GPIOB 引脚14
#define Key4 PBin(15)      // 按键4 对应 GPIOB 引脚15

/* 下面声明 Key.c 中定义的函数（对外接口） */
void Key_Init(void);                     // 初始化按键引脚（上拉输入）

unsigned char Key_GetNum(void);          // 轮询扫描：返回按下的按键编号 1~4（无按键返回0）
unsigned char Key_GetState(void);        // 状态机扫描：按下期间只返回一次，适合做加减计数
unsigned char Key_One(void);             // 综合状态机：区分 长按(1)/短按(2)/双击(3)
unsigned char Key_Oneneed(void);         // 等待一次按下，带 200ms 超时（供 Key_One 内部调用）



#endif
